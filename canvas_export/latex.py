"""Generate TeX-owned panel headings over read-only native PDF exports."""
from __future__ import annotations

import math
import re
from numbers import Real
from typing import Any

from .errors import ExportError


_TEX_REPLACEMENTS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
_LETTERS = re.compile(r"[A-Za-z]+")
_LABEL = re.compile(r"[A-Za-z0-9:_-]+")
_FILENAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]*")
_RESERVED_MACROS = {
    "CanvasExportPanelAt", "CanvasExportPanelScope", "thenspanel", "theHnspanel",
}


def tex_escape(text: str) -> str:
    """Escape title text once, without interpreting it as TeX source."""
    if not isinstance(text, str):
        raise ExportError("Panel title must be a string.")
    return "".join(_TEX_REPLACEMENTS.get(char, char) for char in text)


def _number(value: Any, description: str) -> float:
    if isinstance(value, bool) or not isinstance(value, Real):
        raise ExportError(f"{description} must be a finite real number, not {value!r}.")
    try:
        result = float(value)
    except (ValueError, OverflowError):
        raise ExportError(f"{description} must be a finite real number.") from None
    if not math.isfinite(result):
        raise ExportError(f"{description} must be a finite real number.")
    return result


def panel_position(
    panel: dict[str, Any], elements: list[dict[str, Any]], exported: dict[str, Any]
) -> tuple[float, float]:
    """Locate a heading in overpic units (one hundredth of rendered width).

    Bounds describe the source scene, including negative origins. Export width
    includes padding on both sides; PDF points and PNG pixel scales are not used.
    Only a unique, undeleted agentDiagram.logicalId is a valid anchor.
    """
    anchor_name = panel.get("anchor")
    if not isinstance(anchor_name, str) or not anchor_name:
        raise ExportError("Panel anchor must be a nonempty agentDiagram.logicalId string.")
    matches = []
    for element in elements:
        if element.get("isDeleted"):
            continue
        custom_data = element.get("customData")
        diagram = custom_data.get("agentDiagram") if isinstance(custom_data, dict) else None
        if isinstance(diagram, dict) and diagram.get("logicalId") == anchor_name:
            matches.append(element)
    if len(matches) != 1:
        raise ExportError(
            f"Panel anchor {anchor_name!r} matched {len(matches)} undeleted elements. "
            "Choose a unique customData.agentDiagram.logicalId in the panel configuration; "
            "native element IDs are not anchor aliases."
        )
    anchor = matches[0]
    if _number(anchor.get("angle", 0), f"Panel anchor {anchor_name!r} angle") != 0:
        raise ExportError(
            f"Panel anchor {anchor_name!r} is rotated; choose an unrotated logicalId anchor."
        )
    anchor_x = _number(anchor.get("x"), f"Panel anchor {anchor_name!r} x")
    anchor_y = _number(anchor.get("y"), f"Panel anchor {anchor_name!r} y")
    dx = _number(panel.get("dx", 0), f"Panel anchor {anchor_name!r} dx")
    dy = _number(panel.get("dy", 0), f"Panel anchor {anchor_name!r} dy")
    bounds = exported.get("bounds")
    if not isinstance(bounds, dict):
        raise ExportError("PDF export metadata must contain normalized source bounds.")
    bounds_x = _number(bounds.get("x"), "PDF source bounds x")
    bounds_y = _number(bounds.get("y"), "PDF source bounds y")
    bounds_width = _number(bounds.get("width"), "PDF source bounds width")
    bounds_height = _number(bounds.get("height"), "PDF source bounds height")
    width = _number(exported.get("width"), "PDF export width")
    padding = _number(exported.get("padding"), "PDF export padding")
    if bounds_width < 0 or bounds_height < 0 or padding < 0 or width <= 0:
        raise ExportError("PDF source bounds and padding must be nonnegative; export width must be positive.")
    x = (anchor_x + dx - bounds_x + padding) / width * 100
    y = (bounds_y + bounds_height + padding - anchor_y - dy) / width * 100
    if not math.isfinite(x) or not math.isfinite(y):
        raise ExportError(f"Panel anchor {anchor_name!r} produces non-finite overpic coordinates.")
    return x, y


def graphics_tex(figures: dict[str, dict], states: dict[str, dict]) -> str:
    """Build graphic macros, skipping figures without a configured macro.

    Each included PDF is named ``<figure-name>.pdf`` alongside this wrapper.
    The calling document loads graphicx, overpic and (for linked references)
    hyperref. Panel scopes and labels are unique across this generated wrapper.
    """
    lines = [
        "% Generated by canvas-export from source bounds and logicalId anchors.",
        r"\newcounter{nspanel}",
        r"\renewcommand{\thenspanel}{\alph{nspanel}}",
        r"\providecommand{\theHnspanel}{}",
        r"\renewcommand{\theHnspanel}{\CanvasExportPanelScope.\arabic{nspanel}}",
        r"\newcommand{\CanvasExportPanelAt}[4]{\put(#1,#2){\makebox(0,0)[lt]{\refstepcounter{nspanel}\label{#3}\sffamily\bfseries\fontsize{9}{10}\selectfont(\thenspanel)\enspace #4}}}",
    ]
    macros: set[str] = set()
    scopes: set[str] = set()
    labels: set[str] = set()
    for name, figure in figures.items():
        macro = figure.get("macro")
        if macro is None or macro == "":
            continue
        if not isinstance(macro, str) or not _LETTERS.fullmatch(macro):
            raise ExportError(f"Figure {name!r}: TeX macro must contain letters only: {macro!r}.")
        if macro in macros or macro in _RESERVED_MACROS:
            raise ExportError(f"Figure {name!r}: duplicate or reserved TeX macro {macro!r}; choose a unique name.")
        macros.add(macro)
        if not isinstance(name, str) or not _FILENAME.fullmatch(name):
            raise ExportError(f"Unsafe PDF figure name {name!r}; use letters, digits, dots, underscores or hyphens.")
        declaration = "\\newcommand{\\" + macro + "}"
        panels = figure.get("panels", [])
        if not isinstance(panels, list):
            raise ExportError(f"Figure {name!r}: panels must be a list.")
        if not panels:
            lines.append(declaration + "{\\includegraphics[width=\\textwidth]{" + name + ".pdf}}")
            continue
        scope = figure.get("panel_scope")
        if not isinstance(scope, str) or not _LETTERS.fullmatch(scope):
            raise ExportError(f"Figure {name!r}: panel scope must contain letters only: {scope!r}.")
        if scope in scopes:
            raise ExportError(f"Figure {name!r}: duplicate panel scope {scope!r}; choose a unique scope for hyperlink IDs.")
        scopes.add(scope)
        state = states.get(name)
        if not isinstance(state, dict) or "elements" not in state or "pdf" not in state:
            raise ExportError(f"Figure {name!r}: panel headings require source elements and PDF export metadata.")
        lines.extend([
            declaration + "{%",
            "\\begingroup\\def\\CanvasExportPanelScope{" + scope + "}\\setcounter{nspanel}{0}%",
            r"\vspace*{12pt}%",
            r"\begin{overpic}[abs,unit=0.01\textwidth,width=\textwidth]{" + name + ".pdf}%",
        ])
        for panel in panels:
            if not isinstance(panel, dict):
                raise ExportError(f"Figure {name!r}: every panel must be an object.")
            label = panel.get("label")
            if not isinstance(label, str) or not _LABEL.fullmatch(label):
                raise ExportError(f"Figure {name!r}: invalid TeX panel label {label!r}; use letters, digits, colon, underscore or hyphen.")
            if label in labels:
                raise ExportError(f"Figure {name!r}: duplicate TeX panel label {label!r}; choose a unique label.")
            labels.add(label)
            title = tex_escape(panel.get("title"))
            x, y = panel_position(panel, state["elements"], state["pdf"])
            lines.append(
                r"\CanvasExportPanelAt{" + f"{x:.5f}" + "}{" + f"{y:.5f}" + "}{" + label + "}{" + title + "}%"
            )
        lines.append(r"\end{overpic}\endgroup}")
    return "\n\n".join(lines) + "\n"
